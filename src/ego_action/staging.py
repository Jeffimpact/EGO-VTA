"""Commit immutable capture bundles and retrieve them with digest verification."""

from __future__ import annotations

import hashlib
import json
import posixpath
import shutil
import tempfile
from pathlib import Path, PurePosixPath

from .common import media_paths, read_json, safe_name, sha256, write_json
from .pipeline import validate


def filesystem(uri):
    try:
        from fsspec.core import url_to_fs
    except ImportError as exc:
        raise ValueError("Install the s3 extra for object-store staging") from exc
    return url_to_fs(uri)


def set_reference(spec, key, value):
    if key.startswith("camera/"):
        spec["cameras"][key.split("/", 1)[1]]["file"] = value
    elif key.startswith("sensor/"):
        spec["sensors"][key.split("/", 1)[1]]["file"] = value
    else:
        spec[key] = value


def stage_capture(manifest, prefix):
    """Publish bytes first and a single readable manifest last. Never use a mutable 'latest' key."""
    manifest = Path(manifest)
    spec = read_json(manifest)
    validate(spec)
    paths = media_paths(spec, manifest.parent)
    digests = {k: sha256(p) for k, p in paths.items()}
    for k, fp in paths.items():
        set_reference(spec, k, "assets/" + digests[k] + fp.suffix.lower())
    spec["staged_input_sha256"] = digests
    body = (json.dumps(spec, sort_keys=True, ensure_ascii=False, indent=2) + "\n").encode()
    revision = hashlib.sha256(body).hexdigest()
    fs, base = filesystem(str(prefix))
    folder = posixpath.join(base, safe_name(spec["episode_id"]), revision)
    final = posixpath.join(folder, "episode.json")
    fs.makedirs(posixpath.join(folder, "assets"), exist_ok=True)
    if not fs.exists(final):
        for k, fp in paths.items():
            key = posixpath.join(folder, "assets", digests[k] + fp.suffix.lower())
            with fs.transaction:
                checksum = hashlib.sha256()
                with fp.open("rb") as inp, fs.open(key, "wb") as out:
                    for block in iter(lambda: inp.read(1024 * 1024), b""):
                        checksum.update(block)
                        out.write(block)
                if checksum.hexdigest() != digests[k]:
                    raise RuntimeError(
                        "An input changed while staging; rerun after the capture is complete"
                    )
        # Local concurrent readers and S3 readers see the manifest only after all assets finish.
        with fs.transaction, fs.open(final, "wb") as out:
            out.write(body)
    return fs.unstrip_protocol(final)


def fetch_capture(uri, destination):
    fs, key = filesystem(str(uri))
    with fs.open(key, "rb") as f:
        spec = json.load(f)
    validate(spec)
    digests = spec.get("staged_input_sha256")
    if not isinstance(digests, dict):
        raise TypeError("Expected an episode manifest generated by ego-vta stage")
    dest = Path(destination)

    def already_fetched():
        if (dest / "episode.json").is_file() and read_json(dest / "episode.json") == spec:
            files = media_paths(spec, dest)
            if all(fp.is_file() and sha256(fp) == digests[name] for name, fp in files.items()):
                return dest / "episode.json"
        raise FileExistsError(
            f"Select a new destination; {dest} has different or incomplete contents"
        )

    paths = media_paths(spec, Path("."))
    if set(paths) != set(digests):
        raise ValueError("Incomplete checksum map in staged manifest")
    for name, rel in paths.items():
        parts = PurePosixPath(rel.as_posix()).parts
        if (
            len(parts) != 2
            or parts[0] != "assets"
            or Path(parts[1]).stem != digests[name]
            or len(digests[name]) != 64
            or any(c not in "0123456789abcdef" for c in digests[name])
        ):
            raise ValueError("Invalid asset reference in staged manifest")
    if dest.exists():
        return already_fetched()
    dest.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=dest.parent) as tmp:
        root = Path(tmp) / "capture"
        (root / "assets").mkdir(parents=True)
        for name, rel in paths.items():
            with (
                fs.open(posixpath.join(posixpath.dirname(key), rel.as_posix()), "rb") as f,
                (root / rel).open("wb") as out,
            ):
                shutil.copyfileobj(f, out, 1024 * 1024)
            if sha256(root / rel) != digests[name]:
                raise ValueError(f"Checksum mismatch for {name}")
        write_json(root / "episode.json", spec)
        try:
            root.rename(dest)
        except OSError:
            if dest.exists():
                return already_fetched()
            raise
    return dest / "episode.json"
